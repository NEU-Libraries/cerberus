# frozen_string_literal: true

require 'fileutils'
require 'open3'

# Builds the Font Awesome the site serves from the upstream release, keeping
# only the glyphs and icon rules the source names. bin/fontawesome-subset runs
# it, and spec/lib/font_awesome_subset_spec.rb fails when an icon is missing
# from the build. See docs/font-awesome.md.
#
# Plain Ruby with no Rails, so the script runs on a host without the bundle.
module FontAwesomeSubset
  UPSTREAM = 'vendor/fontawesome-upstream'
  TARGET   = 'vendor/fontawesome'
  MANIFEST = 'vendor/fontawesome-icons.txt'
  STYLESHEET = 'css/all.min.css'
  FONTS = %w[fa-solid-900 fa-regular-400 fa-brands-400].freeze

  # The upstream stylesheet also declares its Font Awesome 4 and 5 family names,
  # for markup written against those releases. The site names only these, and
  # the critical CSS inlines every @font-face on every page.
  FAMILIES = ['Font Awesome 6 Free', 'Font Awesome 6 Brands'].freeze

  # app/assets/builds is compiled output and gitignored, so scanning it would
  # make the name list differ between checkouts.
  SCAN = %w[app config lib].freeze
  SKIP = %r{\Aapp/assets/builds/}

  ICON_RULE = /([^{}]+)\{content:"\\([0-9a-f]+)"\}/
  ICON_SELECTOR = /\A\.(fa-[a-z0-9-]+)::?before\z/
  FONT_FACE = /@font-face\{[^}]*\}/

  module_function

  # Every fa- token in the source. Most are not icons (fa-solid, fa-fw, fa-2x);
  # used_icons keeps only those the stylesheet maps to a glyph.
  def names(root)
    SCAN.flat_map { |dir| Dir.glob("#{dir}/**/*", base: root) }
        .reject { |path| path.match?(SKIP) || File.directory?(File.join(root, path)) }
        .flat_map { |path| File.binread(File.join(root, path)).scan(/\bfa-[a-z0-9-]+/) }
        .to_set
  end

  # Icon name => hex codepoint, from the .fa-x::before rules of a stylesheet.
  def icons(css)
    css.scan(ICON_RULE).each_with_object({}) do |(selectors, codepoint), map|
      selectors.split(',').each do |selector|
        name = selector.strip[ICON_SELECTOR, 1]
        map[name] = codepoint if name
      end
    end
  end

  # The upstream stylesheet without the icon rules and @font-face families the
  # source does not use. A rule with any selector that is not a plain icon is
  # kept whole.
  def trim(css, used)
    trimmed = css.gsub(ICON_RULE) { |rule| trim_icon_rule(rule, *Regexp.last_match.captures, used) }
    trimmed.gsub(FONT_FACE) { |rule| FAMILIES.any? { |family| rule.include?(%(font-family:"#{family}")) } ? rule : '' }
  end

  def trim_icon_rule(rule, selectors, codepoint, used)
    names = selectors.split(',').map { |selector| selector.strip[ICON_SELECTOR, 1] }
    return rule if names.include?(nil)

    kept = names.select { |name| used.include?(name) }
    kept.empty? ? '' : %(#{kept.map { |name| ".#{name}:before" }.join(',')}{content:"\\#{codepoint}"})
  end

  def upstream_css(root) = File.read(File.join(root, UPSTREAM, STYLESHEET))

  def used_icons(root)
    used = names(root)
    icons(upstream_css(root)).slice(*used).sort.to_h
  end

  def manifest(root)
    path = File.join(root, MANIFEST)
    File.exist?(path) ? File.readlines(path, chomp: true).grep_v(/\A#|\A\z/).to_set : Set.new
  end

  # Builds beside the served copy and swaps it in only once every font is cut,
  # so a failed pyftsubset leaves vendor/fontawesome as it was. The staging
  # directory is a sibling so the swap is a rename on one filesystem.
  def build(root, pyftsubset: 'pyftsubset')
    icons = used_icons(root)
    target = File.join(root, TARGET)
    staging = "#{target}.build"
    FileUtils.rm_rf(staging)
    write_build(root, staging, icons, pyftsubset)
    FileUtils.rm_rf(target)
    File.rename(staging, target)
    File.write(File.join(root, MANIFEST), manifest_text(icons))
    icons
  ensure
    FileUtils.rm_rf(staging) if staging
  end

  def write_build(root, dir, icons, pyftsubset)
    FileUtils.mkdir_p(%w[css webfonts].map { |sub| File.join(dir, sub) })
    File.write(File.join(dir, STYLESHEET), trim(upstream_css(root), names(root)))
    FONTS.each { |font| subset(root, dir, font, unicodes(icons), pyftsubset) }
  end

  def unicodes(icons) = icons.values.uniq.sort.map { |codepoint| "U+#{codepoint}" }.join(',')

  def subset(root, dir, font, unicodes, pyftsubset)
    source = File.join(root, UPSTREAM, 'webfonts', "#{font}.ttf")
    { 'ttf' => [], 'woff2' => ['--flavor=woff2'] }.each do |ext, flags|
      output = File.join(dir, 'webfonts', "#{font}.#{ext}")
      _out, err, status = Open3.capture3(pyftsubset, source, "--unicodes=#{unicodes}",
                                         "--output-file=#{output}", *flags)
      raise "#{pyftsubset} failed on #{font}.#{ext}:\n#{err}" unless status.success?
    end
  end

  def manifest_text(icons)
    header = "# Generated by bin/fontawesome-subset. The icons the served Font Awesome carries.\n"
    header + icons.keys.map { |name| "#{name}\n" }.join
  end
end
