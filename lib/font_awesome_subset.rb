# frozen_string_literal: true

require 'fileutils'
require 'open3'

# Builds the Font Awesome the site serves from the upstream release, keeping
# only the glyphs the source names. bin/fontawesome-subset runs it, and
# spec/lib/font_awesome_subset_spec.rb fails when an icon is missing from the
# build. See docs/font-awesome.md.
#
# Plain Ruby with no Rails, so the script runs on a host without the bundle.
module FontAwesomeSubset
  UPSTREAM = 'vendor/fontawesome-upstream'
  TARGET   = 'vendor/fontawesome'
  MANIFEST = 'vendor/fontawesome-icons.txt'
  STYLESHEET = 'css/all.min.css'
  FONTS = %w[fa-solid-900 fa-regular-400 fa-brands-400 fa-v4compatibility].freeze

  # app/assets/builds is compiled output and gitignored, so scanning it would
  # make the name list differ between checkouts.
  SCAN = %w[app config lib].freeze
  SKIP = %r{\Aapp/assets/builds/}

  ICON_RULE = /([^{}]+)\{content:"\\([0-9a-f]+)"\}/
  ICON_SELECTOR = /\A\.(fa-[a-z0-9-]+)::?before\z/

  module_function

  # Every fa- token in the source. Most are not icons (fa-solid, fa-fw, fa-2x);
  # used_icons keeps only those the stylesheet maps to a glyph.
  def names(root)
    SCAN.flat_map { |dir| Dir.glob("#{dir}/**/*", base: root) }
        .reject { |path| path.match?(SKIP) || File.directory?(File.join(root, path)) }
        .flat_map { |path| File.binread(File.join(root, path)).scan(/\bfa-[a-z0-9-]+/) }
        .to_set
  end

  # Icon name => hex codepoint, from the .fa-x::before rules of a stylesheet.
  def icons(css)
    css.scan(ICON_RULE).each_with_object({}) do |(selectors, codepoint), map|
      selectors.split(',').each do |selector|
        name = selector.strip[ICON_SELECTOR, 1]
        map[name] = codepoint if name
      end
    end
  end

  def upstream_css(root) = File.read(File.join(root, UPSTREAM, STYLESHEET))

  def used_icons(root)
    used = names(root)
    icons(upstream_css(root)).slice(*used).sort.to_h
  end

  def manifest(root)
    path = File.join(root, MANIFEST)
    File.exist?(path) ? File.readlines(path, chomp: true).grep_v(/\A#|\A\z/).to_set : Set.new
  end

  def build(root, pyftsubset: 'pyftsubset')
    icons = used_icons(root)
    unicodes = icons.values.uniq.sort.map { |cp| "U+#{cp}" }.join(',')

    FileUtils.rm_rf(File.join(root, TARGET))
    FileUtils.mkdir_p(File.join(root, TARGET, 'css'))
    FileUtils.mkdir_p(File.join(root, TARGET, 'webfonts'))
    File.write(File.join(root, TARGET, STYLESHEET), upstream_css(root))
    FONTS.each { |font| subset(root, font, unicodes, pyftsubset) }
    File.write(File.join(root, MANIFEST), manifest_text(icons))
    icons
  end

  def subset(root, font, unicodes, pyftsubset)
    source = File.join(root, UPSTREAM, 'webfonts', "#{font}.ttf")
    { 'ttf' => [], 'woff2' => ['--flavor=woff2'] }.each do |ext, flags|
      output = File.join(root, TARGET, 'webfonts', "#{font}.#{ext}")
      _out, err, status = Open3.capture3(pyftsubset, source, "--unicodes=#{unicodes}",
                                         "--output-file=#{output}", *flags)
      raise "#{pyftsubset} failed on #{font}.#{ext}:\n#{err}" unless status.success?
    end
  end

  def manifest_text(icons)
    header = "# Generated by bin/fontawesome-subset. The icons the served Font Awesome carries.\n"
    header + icons.keys.map { |name| "#{name}\n" }.join
  end
end
